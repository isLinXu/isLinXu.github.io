import { useEffect } from "react";

const SITE_URL = "https://islinxu.github.io";

function upsertMeta(
  selector: string,
  attribute: "name" | "property",
  key: string,
  content: string
) {
  let element = document.head.querySelector<HTMLMetaElement>(selector);

  if (!element) {
    element = document.createElement("meta");
    element.setAttribute(attribute, key);
    document.head.appendChild(element);
  }

  element.setAttribute("content", content);
}

function upsertLink(selector: string, rel: string, href: string) {
  let element = document.head.querySelector<HTMLLinkElement>(selector);

  if (!element) {
    element = document.createElement("link");
    element.setAttribute("rel", rel);
    document.head.appendChild(element);
  }

  element.setAttribute("href", href);
}

/**
 * Keeps <title> and the main SEO / social meta tags in sync with the page
 * currently rendered on the client. The static tags generated by
 * scripts/prerender.mjs stay as the fallback for crawlers that do not execute
 * JavaScript.
 */
export default function useDocumentMeta(title: string, description?: string) {
  useEffect(() => {
    document.title = title;

    const pathname = window.location.pathname.replace(/\/+$/, "") || "/";
    const url = `${SITE_URL}${pathname}`;

    upsertMeta('meta[property="og:url"]', "property", "og:url", url);
    upsertLink('link[rel="canonical"]', "canonical", url);

    if (!description) {
      return;
    }

    upsertMeta('meta[name="description"]', "name", "description", description);
    upsertMeta('meta[property="og:title"]', "property", "og:title", title);
    upsertMeta(
      'meta[property="og:description"]',
      "property",
      "og:description",
      description
    );
    upsertMeta('meta[name="twitter:title"]', "name", "twitter:title", title);
    upsertMeta(
      'meta[name="twitter:description"]',
      "name",
      "twitter:description",
      description
    );
  }, [title, description]);
}
